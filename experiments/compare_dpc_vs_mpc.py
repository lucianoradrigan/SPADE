"""DPC v3 / v4 vs. the ported upstream CCS-MPC on SPADE's VSC plant -- TODO_CLAUDE_CODE.md V2.

Grid: the loads of tests/test_dpc_robustness_grid.py and experiments/measure_dpc_rmse_by_r_range.py
(R = 3.5 ohm ... 5 kohm, all above the open-loop limit R* = 3.3707 ohm) x |v_ref| = 10, 35, 50,
120, 150 V, at 50 Hz, 2000 steps (0.2 s) each, from a zero initial state.

Controllers:
- MPC N=5: control/mpc/vsc_ccs_mpc.py with the upstream horizon and weights, no voltage limit;
- MPC N=5, +-134 V: the same with the upstream per-axis clamp (S-09);
- MPC N=1: one-step horizon, no limit;
- DPC v3 and DPC v4 (default): configs/dpc_trained_v{3,4}*.weights.h5, which have no limit.

Metrics, all per condition:
- settled_rmse_v: RMS of |v_c - v_ref| after 50 warm-up steps. Same alignment as
  measure_dpc_rmse_by_r_range.py: the state after step k against reference k.
- thd_pct: total harmonic distortion of v_c,alpha, harmonics 2-40, over the last 1800 steps
  (9 whole cycles at 50 Hz).
- effort_rms_v: RMS of |v_o|. effort_max_axis_v: max per-axis |v_o|. Both over the settled window.
- cpu_us_per_step: mean wall time of one control() call on this machine (single thread).

Usage:

    python experiments/compare_dpc_vs_mpc.py --out-dir docs/audit/stability
"""

from __future__ import annotations

import argparse
import json
import os
import platform
import sys
import time
from pathlib import Path

os.environ.setdefault("TF_CPP_MIN_LOG_LEVEL", "2")

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from driveflow.control.dpc.controller import DpcController  # noqa: E402
from driveflow.control.dpc.reference import RotatingReference  # noqa: E402
from driveflow.control.mpc.vsc_ccs_mpc import UPSTREAM_VOLTAGE_LIMIT_V, VscCcsMpc  # noqa: E402
from driveflow.sim.vsc_system import VscSystem  # noqa: E402

R_GRID = [3.5, 4.0, 5.0, 8.0064, 10.0, 20.0, 40.0, 100.0, 1000.0, 5000.0]
MAGNITUDES = [10.0, 35.0, 50.0, 120.0, 150.0]
N_STEPS = 2000
WARMUP = 50
THD_SAMPLES = 1800  # 9 cycles of 50 Hz at Ts = 100 us
THD_MAX_HARMONIC = 40

CONTROLLERS = {
    "MPC N=5": lambda r: VscCcsMpc(r),
    f"MPC N=5, ±{UPSTREAM_VOLTAGE_LIMIT_V:g} V": lambda r: VscCcsMpc(r, voltage_limit_v=UPSTREAM_VOLTAGE_LIMIT_V),
    "MPC N=1": lambda r: VscCcsMpc(r, horizon=1),
    "DPC v3": lambda r: DpcController(ROOT / "configs" / "dpc_trained_v3_closed_loop.weights.h5", r_ohm=r),
    "DPC v4 (default)": lambda r: DpcController(ROOT / "configs" / "dpc_trained_v4_r_range.weights.h5", r_ohm=r),
}


def thd_pct(x: np.ndarray, fundamental_bin: int) -> float:
    spec = np.abs(np.fft.rfft(x))
    harmonics = [spec[h * fundamental_bin] for h in range(2, THD_MAX_HARMONIC + 1) if h * fundamental_bin < len(spec)]
    return float(100.0 * np.sqrt(np.sum(np.square(harmonics))) / spec[fundamental_bin])


def run(controller, r_ohm: float, magnitude_v: float) -> dict:
    system = VscSystem(load_resistance_ohm=r_ohm)
    reference = RotatingReference(magnitude_v=magnitude_v)
    state = system.reset()
    controller.reset()
    vc = np.empty((N_STEPS, 2))
    vref = np.empty((N_STEPS, 2))
    u = np.empty((N_STEPS, 2))
    t_ctrl = 0.0
    with np.errstate(over="ignore", invalid="ignore"):
        for k in range(N_STEPS):
            t0 = time.perf_counter()
            u[k] = controller.control(state, reference, k)
            t_ctrl += time.perf_counter() - t0
            state = system.simulate(*u[k])
            vc[k] = state.vc_real, state.vc_imag
            vref[k] = reference.at_step(k)
    err = np.hypot(*(vc - vref).T)
    finite = bool(np.all(np.isfinite(err)) and np.all(np.isfinite(u)))
    settled = slice(WARMUP, None)
    out = {"finite": finite, "cpu_us_per_step": 1e6 * t_ctrl / N_STEPS}
    if not finite:
        return {**out, "settled_rmse_v": None, "thd_pct": None, "effort_rms_v": None, "effort_max_axis_v": None}
    cycles = round(THD_SAMPLES * 1e-4 * 50.0)
    return {
        **out,
        "settled_rmse_v": float(np.sqrt(np.mean(err[settled] ** 2))),
        "thd_pct": thd_pct(vc[-THD_SAMPLES:, 0], cycles),
        "effort_rms_v": float(np.sqrt(np.mean(np.sum(u[settled] ** 2, axis=1)))),
        "effort_max_axis_v": float(np.max(np.abs(u[settled]))),
    }


def _fmt(v, nd=2):
    return "diverged" if v is None else f"{v:.{nd}f}"


def write_markdown(res: dict, path: Path):
    names = list(CONTROLLERS)
    lines = [
        "# DPC vs. ported upstream CCS-MPC (V2)",
        "",
        "Generated by `python experiments/compare_dpc_vs_mpc.py`. Raw values: [`dpc_vs_mpc.json`](dpc_vs_mpc.json); figure: [`dpc_vs_mpc.png`](dpc_vs_mpc.png).",
        f"Plant: SPADE's averaged VSC model (ADF/BDF), {N_STEPS} steps (0.2 s) from rest, 50 Hz reference. RMSE after {WARMUP} warm-up steps; THD over the last {THD_SAMPLES} steps (9 cycles), harmonics 2-{THD_MAX_HARMONIC}.",
        "",
        "## Settled RMSE of v_c (V)",
        "",
        "| R (Ω) | \\|v_ref\\| (V) | " + " | ".join(names) + " |",
        "|---|---|" + "---|" * len(names),
    ]
    for key, row in res["grid"].items():
        r, v = row["r_ohm"], row["magnitude_v"]
        lines.append(f"| {r:g} | {v:g} | " + " | ".join(_fmt(row[n]["settled_rmse_v"]) for n in names) + " |")
    for metric, title, nd in (("thd_pct", "THD of v_c,α (%)", 2), ("effort_rms_v", "Control effort, RMS |v_o| (V)", 1), ("effort_max_axis_v", "Max per-axis |v_o| (V)", 1)):
        lines += ["", f"## {title}, \\|v_ref\\| = 50 V and 150 V", "", "| R (Ω) | \\|v_ref\\| (V) | " + " | ".join(names) + " |", "|---|---|" + "---|" * len(names)]
        for row in res["grid"].values():
            if row["magnitude_v"] in (50.0, 150.0):
                lines.append(f"| {row['r_ohm']:g} | {row['magnitude_v']:g} | " + " | ".join(_fmt(row[n][metric], nd) for n in names) + " |")
    lines += ["", "## CPU time per control step (µs, mean over the grid)", "", "| Controller | µs/step |", "|---|---|"]
    for n in names:
        lines.append(f"| {n} | {res['cpu_us_per_step_mean'][n]:.1f} |")
    lines += ["", f"Machine: {res['machine']}.",
              "The DPC time is one eager Keras call per step (control/dpc/controller.py) and is dominated by framework overhead, not by the network's ~700 multiply-adds, so it is not an estimate of embedded cost. The MPC is one precomputed gain row per axis.",
              "THD is only meaningful where tracking is bounded (DPC v3 above ~100 Ω is not).", ""]
    path.write_text("\n".join(lines))


def plot(res: dict, path: Path):
    """Settled RMSE vs. R at 50 V and 150 V (plotly + kaleido, the same stack and style as
    experiments/run_stability_battery.py)."""
    import plotly.graph_objects as go
    from plotly.subplots import make_subplots

    from experiments.run_stability_battery import COLORS, GRID, INK, MUTED, SURFACE

    colors = COLORS + ["#8a5cd1"]  # five controllers, five distinct hues
    dashes = ["solid", "dash", "dot", "solid", "dashdot"]

    fig = make_subplots(rows=1, cols=2, shared_yaxes=True, subplot_titles=("|v_ref| = 50 V", "|v_ref| = 150 V"))
    for col, mag in enumerate((50.0, 150.0), start=1):
        rows = [row for row in res["grid"].values() if row["magnitude_v"] == mag]
        for i, name in enumerate(CONTROLLERS):
            ys = [row[name]["settled_rmse_v"] for row in rows]
            fig.add_trace(go.Scatter(x=[row["r_ohm"] for row in rows], y=ys, mode="lines+markers", name=name, showlegend=col == 1,
                                     line=dict(color=colors[i], width=2, dash=dashes[i]), marker=dict(size=7)), row=1, col=col)
    fig.update_layout(title=dict(text="VSC tracking: ported upstream CCS-MPC vs. DPC v3 / v4 (SPADE averaged plant)", font=dict(color=INK, size=16)),
                      paper_bgcolor=SURFACE, plot_bgcolor=SURFACE, font=dict(color=MUTED, size=12), width=1100, height=480,
                      margin=dict(l=70, r=30, t=70, b=60), legend=dict(bgcolor=SURFACE, font=dict(color=INK)))
    fig.update_xaxes(title="Load resistance R (Ω)", type="log", gridcolor=GRID, zeroline=False, linecolor=MUTED)
    fig.update_yaxes(type="log", gridcolor=GRID, zeroline=False, linecolor=MUTED)
    fig.update_yaxes(title="Settled RMSE of v_c (V)", row=1, col=1)
    fig.write_image(path)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out-dir", type=Path, default=ROOT / "docs" / "audit" / "stability")
    ap.add_argument("--from-json", action="store_true", help="re-render the markdown and figure from an existing dpc_vs_mpc.json")
    args = ap.parse_args(argv)
    args.out_dir.mkdir(parents=True, exist_ok=True)
    if args.from_json:
        res = json.loads((args.out_dir / "dpc_vs_mpc.json").read_text())
        write_markdown(res, args.out_dir / "dpc_vs_mpc.md")
        plot(res, args.out_dir / "dpc_vs_mpc.png")
        return

    grid = {}
    cpu = {n: [] for n in CONTROLLERS}
    for r in R_GRID:
        for mag in MAGNITUDES:
            row = {"r_ohm": r, "magnitude_v": mag}
            for name, make in CONTROLLERS.items():
                row[name] = run(make(r), r, mag)
                cpu[name].append(row[name]["cpu_us_per_step"])
            grid[f"R={r:g},V={mag:g}"] = row
            print(f"R={r:>7g} |v_ref|={mag:>4g}  " + "  ".join(f"{n}: {_fmt(row[n]['settled_rmse_v'])}" for n in CONTROLLERS), flush=True)

    res = {
        "n_steps": N_STEPS, "warmup": WARMUP, "thd_samples": THD_SAMPLES,
        "machine": f"{platform.processor() or platform.machine()}, {platform.system()} {platform.release()}, Python {platform.python_version()}",
        "cpu_us_per_step_mean": {n: float(np.mean(v)) for n, v in cpu.items()},
        "grid": grid,
    }
    (args.out_dir / "dpc_vs_mpc.json").write_text(json.dumps(res, indent=2) + "\n")
    write_markdown(res, args.out_dir / "dpc_vs_mpc.md")
    plot(res, args.out_dir / "dpc_vs_mpc.png")
    print("wrote", args.out_dir / "dpc_vs_mpc.{json,md,png}")


if __name__ == "__main__":
    main()
