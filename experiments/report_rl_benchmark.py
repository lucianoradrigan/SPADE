"""RL benchmark report -- expansion task E8. Writes docs/audit/expansion/e8_rl_benchmark.{md,json}.

Each training is a real ``rl_training`` job, run by an in-process worker in its own scratch
workspace. The jobs run in parallel processes, with 2 TensorFlow threads each. The job itself
benchmarks the final policy against the classical controllers on the same environment and grid:
- buck: the PI cascade;
- VSC: DPC v3 and DPC v4.
The policy is published as a candidate even if it loses; nothing becomes a default.

    python experiments/report_rl_benchmark.py [--episodes 100] [--jobs 5]
"""

from __future__ import annotations

import argparse
import json
import multiprocessing as mp
import os
import platform
import tempfile
import time
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "audit" / "expansion"
DEFAULT_REWARD = None  # the environments' default terms (envs/reward.DEFAULT_TERMS)
RUNS = (
    ("buck_ddpg_seed0", "SPADE/Buck-v0", "ddpg", 0, {}),
    ("buck_ddpg_seed1", "SPADE/Buck-v0", "ddpg", 1, {}),
    ("buck_ddpg_seed2", "SPADE/Buck-v0", "ddpg", 2, {}),
    ("buck_dqn_seed0", "SPADE/Buck-v0", "dqn", 0, {"discrete_levels": 21}),
    ("vsc_ddpg_seed0", "SPADE/Vsc-v0", "ddpg", 0, {}),
)


def _one(args) -> dict:
    name, env_id, algo, seed, extra, episodes = args
    os.environ["SPADE_WORKSPACE"] = tempfile.mkdtemp(prefix=f"spade_e8_{name}_")
    import tensorflow as tf

    tf.config.threading.set_intra_op_parallelism_threads(2)
    tf.config.threading.set_inter_op_parallelism_threads(2)
    from driveflow.jobs.service import JobService
    from driveflow.jobs.worker import Worker
    from driveflow.runs.schemas import ExperimentSpec

    s = JobService()
    job = s.submit(ExperimentSpec.create("rl_training", algorithm=algo, seed=seed, params={"env_id": env_id, "episodes": episodes, "eval_every": 10, **extra}))
    t0 = time.perf_counter()
    Worker().serve(once=True, poll_s=0.05)
    run = s.run_for(s.get(job.job_id))

    def art(suffix):
        a = next(a for a in run.artifacts if a["path"].endswith(suffix))
        return json.loads(s.store.artifact_path(a).read_text())

    return {"name": name, "env_id": env_id, "algorithm": algo, "seed": seed, "extra": extra, "status": run.status, "wall_s": round(time.perf_counter() - t0, 1),
            "history": art("history.json"), "benchmark": art("benchmark.json"), "metrics": run.metrics}


def main(argv=None) -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--episodes", type=int, default=100)
    ap.add_argument("--jobs", type=int, default=5)
    ap.add_argument("--out", type=Path, default=OUT)
    ap.add_argument("--render-only", action="store_true", help="re-render the .md from the existing .json (no training)")
    args = ap.parse_args(argv)
    if args.render_only:
        rep = json.loads((args.out / "e8_rl_benchmark.json").read_text())
        (args.out / "e8_rl_benchmark.md").write_text(render(rep))
        print(render(rep))
        return
    t0 = time.perf_counter()
    with ProcessPoolExecutor(max_workers=args.jobs, mp_context=mp.get_context("spawn")) as pool:
        results = list(pool.map(_one, [(*r, args.episodes) for r in RUNS]))
    rep = {"meta": {"command": f"python experiments/report_rl_benchmark.py --episodes {args.episodes} --jobs {args.jobs}", "date": time.strftime("%Y-%m-%d"),
                    "machine": f"{platform.system()} {platform.machine()}, Python {platform.python_version()}", "total_wall_s": round(time.perf_counter() - t0, 1),
                    "reward": "environment default terms: tracking 1.0, overcurrent 10.0 (threshold 0.8), action_rate 0.01"},
           "runs": results}
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / "e8_rl_benchmark.json").write_text(json.dumps(rep, default=float))
    (args.out / "e8_rl_benchmark.md").write_text(render(rep))
    print(render(rep))


def _f(x, spec=".3f"):
    return "—" if x is None else format(x, spec)


def render(rep: dict) -> str:
    L = ["# E8: RL Lab benchmark (DQN, DDPG) against the classical controllers", "",
         f"Generated by `{rep['meta']['command']}` on {rep['meta']['date']} ({rep['meta']['machine']}), {rep['meta']['total_wall_s']} s of wall time. "
         "Raw values: [`e8_rl_benchmark.json`](e8_rl_benchmark.json).", "",
         "Each training is a real `rl_training` job. The benchmark runs every controller through the same environment (plant, limits, timestep, reward terms) on the same condition grid. "
         f"Reward: {rep['meta']['reward']}. Simulated plants only. **The policies are candidates: none is used as a default.**", ""]
    for env_id in dict.fromkeys(r["env_id"] for r in rep["runs"]):
        runs = [r for r in rep["runs"] if r["env_id"] == env_id]
        L += [f"## {env_id}", "", "| Training run | Episodes | Final eval reward | Controller | Mean episode reward on the grid | Median tracking RMSE (2nd half) | Terminated conditions |", "|---|---|---|---|---|---|---|"]
        for r in runs:
            h = r["history"]
            for ctrl, s in r["benchmark"]["summary"].items():
                L.append(f"| {r['name']} | {len(h['episode_reward'])} | {_f(h['eval_reward'][-1] if h['eval_reward'] else None, '.2f')} | {ctrl} | {_f(s['mean_reward'], '.2f')} | "
                         f"{_f(s['median_tracking_rmse'])} V | {s['n_terminated']}/{s['n_conditions']} |")
        L += ["", "Per condition (tracking RMSE in V, second half; termination):", "", "| Run | Controller | " + " | ".join(
            ", ".join(f"{k}={v:g}" for k, v in c.items() if k != "phase0_rad") for c in runs[0]["benchmark"]["grid"]) + " |", "|---|---|" + "---|" * len(runs[0]["benchmark"]["grid"])]
        for r in runs:
            for ctrl, rows in r["benchmark"]["results"].items():
                if ctrl != list(r["benchmark"]["results"])[0] and r is not runs[0]:
                    continue  # the classical baselines are identical across runs: show them once
                L.append(f"| {r['name']} | {ctrl} | " + " | ".join(f"{_f(x['tracking_rmse_second_half'])}{' (' + x['termination'] + ')' if x['termination'] else ''}" for x in rows) + " |")
        L.append("")
    seeds = [r for r in rep["runs"] if r["env_id"] == "SPADE/Buck-v0" and r["algorithm"] == "ddpg"]
    if len(seeds) > 1:
        vals = [s["benchmark"]["summary"]["RL (DDPG)"]["median_tracking_rmse"] for s in seeds]
        L += ["## Seed sensitivity (buck, DDPG)", "", "| Seed | Median tracking RMSE (V) | Mean grid reward |", "|---|---|---|"]
        for s, v in zip(seeds, vals):
            L.append(f"| {s['seed']} | {_f(v)} | {_f(s['benchmark']['summary']['RL (DDPG)']['mean_reward'], '.2f')} |")
        L.append("")
    L += ["## Reading", "",
          "- **Buck: RL loses on steady-state tracking.** The PI reaches 0.19 V median RMSE in the second half of every condition; DQN 0.49 V and DDPG 0.9–4.6 V depending on the seed.",
          "- **Reward and tracking disagree.** DQN (−3.10) and DDPG seed 1 (−4.66) score a *better* mean episode reward than the PI (−5.03), because the reward covers the whole episode "
          "(start-up included) and adds the action-rate term, while the RMSE column measures the second half only; which part of the episode makes the difference was not decomposed. "
          "A policy that wins on reward is not thereby a better regulator; both numbers are reported.",
          "- **Seed sensitivity is large** for DDPG on the buck (median RMSE 0.93–4.62 V over seeds 0–2 with the same budget).",
          "- **VSC: RL is far from the DPC networks** (median RMSE 21.5 V against 13.2 V for DPC v3 and 2.8 V for DPC v4) after 100 episodes; the DPC networks were trained on the identified model "
          "with a differentiable predictive-control loss, which a model-free agent with this budget does not match.",
          "- Training budget: 100 episodes per run (1000 steps each), seed per run as listed, 2 TF threads per process. Longer training was not tried.", ""]
    return "\n".join(L) + "\n"


if __name__ == "__main__":
    main()
