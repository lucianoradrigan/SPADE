"""A2 evidence: the researcher kit's single command and the ingestion, run against the FAKE PLECS server
(tests/integrations/plecs/fake_plecs.py) for the Buck template and the DAB template.
PLECS real: not executed -- it requires the researcher's machine.

    python experiments/report_a2_researcher_kit.py
Writes docs/audit/plecs_om/a2_researcher_kit.{md,json}. Everything else goes to a temporary folder.
"""

import json
import platform
import sys
import tempfile
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tests" / "integrations" / "plecs"))
sys.path.insert(0, str(ROOT / "experiments"))


def main():
    from fake_plecs import FakePlecs

    import ingest_plecs_evidence
    import plecs_researcher_run

    tmp = Path(tempfile.mkdtemp(prefix="spade_a2_"))
    rows = []
    for name, tpl, circuit in (("Buck", "buck_example.yaml", "my_buck.plecs"), ("DAB", "dab_example.yaml", "DAB_sample1.plecs")):
        c = tmp / circuit
        c.write_text("placeholder circuit for the fake PLECS server\n")
        out = tmp / f"results_{name}"
        with FakePlecs() as fake:
            plecs_researcher_run.main(["--circuit", str(c), "--manifest", str(ROOT / "configs" / "plecs" / "manifest_templates" / tpl), "--out", str(out), "--rpc-url", fake.url])
        zp = next(out.glob("plecs_evidence_*.zip"))
        with zipfile.ZipFile(zp) as z:
            ev = json.loads(z.read("evidence.json"))
            members = sorted(z.namelist())
        rc = ingest_plecs_evidence.main([str(zp), "--docs-root", str(tmp / "docs"), "--data-root", str(tmp / "data")])
        s = ev["steps"]
        rows.append({"circuit": name, "template": tpl, "status": ev["status"], "sweep_ok": f"{s['sweep']['n_ok']}/{s['sweep']['n_conditions']}",
                     "surrogate": s["surrogate"].get("env_id") or s["surrogate"].get("skipped"), "check_env": s["surrogate"].get("check_env_passed"),
                     "compare_rows": len((s.get("compare_with_spade") or {}).get("rows") or []), "members": len(members), "ingest_exit_code": rc,
                     "plecs_version_reported": ev["versions"]["plecs"], "zip_bytes": zp.stat().st_size})
    rep = {"command": "python experiments/report_a2_researcher_kit.py", "machine": f"{platform.system()} {platform.machine()}, Python {platform.python_version()}",
           "source": "fake PLECS server (test double) -- PLECS real: no ejecutado: requiere la máquina del investigador", "rows": rows}
    out = ROOT / "docs" / "audit" / "plecs_om"
    (out / "a2_researcher_kit.json").write_text(json.dumps(rep, indent=2))
    L = ["# A2 — PLECS researcher kit", "",
         f"Generated by `{rep['command']}` ({rep['machine']}). Raw values: [`a2_researcher_kit.json`](a2_researcher_kit.json).", "",
         "**Run against the fake PLECS server only.** **PLECS real: no ejecutado: requiere la máquina del investigador.**", "",
         "- **Kit:** guide [`docs/guides/PLECS_RESEARCHER_KIT.md`](../../guides/PLECS_RESEARCHER_KIT.md); command `experiments/plecs_researcher_run.py`; ingestion `experiments/ingest_plecs_evidence.py`; templates `configs/plecs/manifest_templates/{buck,dab}_example.yaml`, both labelled EXAMPLE CONFIGURATION — NOT EXECUTED.",
         "- **Tests:** `tests/integrations/plecs/test_researcher_kit.py` (9). They cover:",
         "  - both templates end to end;",
         "  - the failure path: an unreachable PLECS still produces a package with the cause;",
         "  - a tampered package, refused on SHA-256;",
         "  - double ingestion, refused;",
         "  - derived expressions limited to arithmetic.", "",
         "| Circuit | Template | Status | Sweep ok | Surrogate | check_env | Compare rows (held-out runs) | Files in zip | Ingest exit code | PLECS version reported |",
         "|---|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        L.append(f"| {r['circuit']} | `{r['template']}` | {r['status']} | {r['sweep_ok']} | {r['surrogate']} | {r['check_env']} | {r['compare_rows']} | {r['members']} | {r['ingest_exit_code']} | {r['plecs_version_reported']} |")
    L += ["", "The fake server reports no version, like real PLECS: there is no documented RPC version command. The DAB returns a dataset only; training its modulation model (E9) is a separate round, with the user's confirmation.", ""]
    (out / "a2_researcher_kit.md").write_text("\n".join(L))
    print("\n".join(L))


if __name__ == "__main__":
    main()
