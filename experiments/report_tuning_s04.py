"""S-04 tuning report -- expansion task E7. Writes docs/audit/expansion/e7_tuning_s04.{md,json}.

Runs the three optimisers as real ``controller_tuning`` jobs in an in-process worker, in a scratch
workspace, with the same budget and seed:
- PSO and Bayesian optimisation on the scalar objective J;
- NSGA-II on (overshoot, settling, dip).
Each best candidate is then compared with the baseline PI (b = 1, 80 rad/s, ζ = 0.9) on the
evaluation grid, which is fixed in optim/objectives.py and is not the tuning grid. A candidate that does
not improve on the evaluation grid is reported as such.

    python experiments/report_tuning_s04.py [--evaluations 96] [--seed 0]
"""

from __future__ import annotations

import argparse
import json
import os
import platform
import tempfile
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "audit" / "expansion"


def main(argv=None) -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--evaluations", type=int, default=96)
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--out", type=Path, default=OUT)
    args = ap.parse_args(argv)
    os.environ["SPADE_WORKSPACE"] = tempfile.mkdtemp(prefix="spade_e7_")

    from driveflow.jobs.service import JobService
    from driveflow.jobs.worker import Worker
    from driveflow.optim import objectives as ob
    from driveflow.runs.schemas import ExperimentSpec

    s = JobService()
    jobs = {}
    for method in ("pso", "bayes", "nsga2"):
        spec = ExperimentSpec.create("controller_tuning", plant_profile_id="native:dc_perm_ex_v1", algorithm=method, seed=args.seed,
                                     params={"bounds": [list(b) for b in ob.BOUNDS]}, budget={"evaluations": args.evaluations})
        jobs[method] = s.submit(spec).job_id
    t0 = time.perf_counter()
    Worker().serve(once=True, poll_s=0.05)
    wall = time.perf_counter() - t0
    out = {"meta": {"command": "python experiments/report_tuning_s04.py " + " ".join(f"--{k.replace('_', '-')} {v}" for k, v in vars(args).items() if k != "out"),
                    "date": time.strftime("%Y-%m-%d"), "machine": f"{platform.system()} {platform.machine()}, Python {platform.python_version()}",
                    "evaluations": args.evaluations, "seed": args.seed, "wall_s_all_three": round(wall, 1),
                    "search_space": dict(zip(ob.PARAMS, ob.BOUNDS)), "baseline": ob.BASELINE,
                    "objective": "J = mean overshoot % + 0.1 x mean settling ms + 2 x mean load dip rad/s",
                    "tuning_grid": [vars(c) for c in ob.TUNING_GRID], "evaluation_grid": [vars(c) for c in ob.EVALUATION_GRID],
                    "grids_overlap": ob.grids_overlap()},
           "methods": {}}
    for method, job_id in jobs.items():
        job = s.get(job_id)
        run = s.run_for(job)
        rep = json.loads(s.store.artifact_path(next(a for a in run.artifacts if a["path"].endswith("tuning_report.json"))).read_text())
        best = min(rep["candidates"], key=lambda c: c["tuning"]["J"])
        out["methods"][method] = {"state": job.state.value, "n_evaluations": run.metrics["n_evaluations"], "best": best,
                                  "n_candidates": len(rep["candidates"]), "pareto": [{"params": c["params"], "objectives": c.get("objectives"),
                                                                                       "evaluation_J": c["evaluation"]["J"]} for c in rep["candidates"]] if method == "nsga2" else None}
        out["baseline"] = rep["baseline"]
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / "e7_tuning_s04.json").write_text(json.dumps(out, indent=1, default=float))
    (args.out / "e7_tuning_s04.md").write_text(render(out))
    print(render(out))


def _f(x, spec=".2f"):
    return "—" if x is None else format(x, spec)


def render(out: dict) -> str:
    b = out["baseline"]
    L = ["# E7: tuning the DC-motor PI speed loop for S-04", "",
         f"Generated by `{out['meta']['command']}` on {out['meta']['date']} ({out['meta']['machine']}); raw values in [`e7_tuning_s04.json`](e7_tuning_s04.json). "
         f"The three runs went through the job worker (`controller_tuning`), {out['meta']['evaluations']} objective evaluations each, seed {out['meta']['seed']}, "
         f"{out['meta']['wall_s_all_three']} s in total.", "",
         "Simulated closed loop only (`validation.benches.run_dc_closed_loop`). Every result is a **candidate**: no default was changed, and 'Use as default' is not authorized in this round (D1).", "",
         f"Search space: {', '.join(f'{k} ∈ [{lo:g}, {hi:g}]' for k, (lo, hi) in out['meta']['search_space'].items())}. Baseline: {out['meta']['baseline']}.",
         f"Objective: {out['meta']['objective']}. Tuning and evaluation grids overlap: {out['meta']['grids_overlap']}.", "",
         "| | Bandwidth (rad/s) | Damping | b | J tuning | J evaluation | Mean overshoot eval (%) | Mean settling eval (ms) | Mean dip eval (rad/s) |", "|---|---|---|---|---|---|---|---|---|",
         f"| Baseline | 80 | 0.9 | 1.0 | {_f(b['tuning']['J'])} | {_f(b['evaluation']['J'])} | {_f(b['evaluation']['mean_overshoot_pct'])} | {_f(b['evaluation']['mean_settling_ms'], '.1f')} | {_f(b['evaluation']['mean_dip_rad_s'])} |"]
    for m, r in out["methods"].items():
        p, e = r["best"]["params"], r["best"]["evaluation"]
        L.append(f"| {m} (best) | {p['speed_bandwidth_rad_s']:.1f} | {p['speed_damping']:.3f} | {p['setpoint_weight']:.3f} | {_f(r['best']['tuning']['J'])} | {_f(e['J'])} | "
                 f"{_f(e['mean_overshoot_pct'])} | {_f(e['mean_settling_ms'], '.1f')} | {_f(e['mean_dip_rad_s'])} |")
    L += ["", "## Evaluation grid, per condition (baseline → best of each method)", "", "| Condition | Metric | Baseline | " + " | ".join(out["methods"]) + " |", "|---|---|---|" + "---|" * len(out["methods"])]
    for i, row in enumerate(b["evaluation_rows"]):
        keys = ("overshoot_pct", "settling_ms") if row["kind"] == "step" else ("dip_rad_s", "final_error_rad_s")
        for k in keys:
            L.append(f"| {row['condition']} | {k} | {_f(row.get(k))} | " + " | ".join(_f(r["best"]["evaluation_rows"][i].get(k)) for r in out["methods"].values()) + " |")
    nd = out["methods"].get("nsga2")
    if nd and nd["pareto"]:
        L += ["", f"## NSGA-II final front ({len(nd['pareto'])} points, first 12 evaluated on the evaluation grid)", "",
              "| b | Bandwidth | Damping | Overshoot (tuning) | Settling ms (tuning) | Dip (tuning) | J evaluation |", "|---|---|---|---|---|---|---|"]
        for c in nd["pareto"]:
            o = c["objectives"]
            L.append(f"| {c['params']['setpoint_weight']:.3f} | {c['params']['speed_bandwidth_rad_s']:.1f} | {c['params']['speed_damping']:.3f} | {o[0]:.2f} | {o[1]:.1f} | {o[2]:.3f} | {_f(c['evaluation_J'])} |")
    L += ["", "## Reading", "",
          "- The objective has no control-effort, current-margin or noise term, so a faster speed loop always reduces the load dip and the optimisers push the bandwidth towards its upper bound. "
          "A candidate at the bound is a property of this objective, not evidence that the faster loop is safe on a real drive.",
          "- The evaluation grid includes plant drift and a current-saturating step; it is the generalisation estimate, the tuning-grid J is not.", ""]
    return "\n".join(L) + "\n"


if __name__ == "__main__":
    main()
