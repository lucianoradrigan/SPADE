"""Where does the DPC loop start to diverge as the filter capacitor degrades? -- finding S-14.

E10b found that the closed loop (ScheduledDpcController on the degraded-capacitor plant,
sim/vsc_faults.py) diverges at C x0.4 at the nominal load while C x0.45 and x0.5 are stable. This
script sweeps the capacitor factor from x0.70 down to x0.40 in steps of 0.01 over the stable loads of
experiments/measure_dpc_rmse_by_r_range.py's R_GRID (R >= 4 ohm; below R* = 3.37 ohm the plant
diverges with or without a controller, S-08) and reports, per load, the largest factor that
diverges and the smallest that stays stable.

Divergence: any non-finite sample, or |v_c| above 10x the reference magnitude in the second half of
the run. Otherwise the run is stable and its second-half RMSE |v_c - v_ref| is recorded.

    python experiments/measure_dpc_capacitor_divergence.py   # writes docs/audit/stability/dpc_capacitor_divergence.{md,json}
"""

from __future__ import annotations

import json
import platform
import time
from pathlib import Path

import numpy as np
import pandas as pd

from driveflow.control.dpc.reference import REFERENCE_MAGNITUDE_V
from driveflow.datagen import Scenario, run_scenario

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "audit" / "stability"
R_GRID = [4.0, 5.0, 8.0064, 10.0, 15.0, 20.0]  # measure_dpc_rmse_by_r_range.R_GRID, stable part (R >= 4 ohm)
C_FACTORS = [round(0.70 - 0.01 * k, 2) for k in range(31)]  # 0.70 ... 0.40
DURATION_S = 0.2
BLOWUP = 10.0


def classify(c_scale: float, r_ohm: float) -> dict:
    with np.errstate(all="ignore"):
        df = pd.DataFrame.from_records(run_scenario(Scenario(scenario_id="s14", controller_type="DPC", plant_config_id="vsc_dpc_v1",
                                                             duration_s=DURATION_S, load_resistance_ohm=r_ohm, vsc_capacitor_scale=c_scale)))
    vc = np.hypot(df["vc_real"].to_numpy(), df["vc_imag"].to_numpy())
    half = len(df) // 2
    finite = bool(np.isfinite(vc).all())
    first_bad = None if finite else float(df["timestamp_s"].iloc[int(np.argmax(~np.isfinite(vc)))])
    peak = float(np.nanmax(vc[half:])) if np.isfinite(vc[half:]).any() else float("inf")
    diverged = (not finite) or peak > BLOWUP * REFERENCE_MAGNITUDE_V
    rmse = None
    if not diverged:
        err = np.hypot(df["vc_real"] - df["v_ref_real"], df["vc_imag"] - df["v_ref_imag"]).to_numpy()[half:]
        rmse = float(np.sqrt(np.mean(err ** 2)))
    return {"c_scale": c_scale, "load_ohm": r_ohm, "diverged": diverged, "first_non_finite_s": first_bad, "peak_vc_second_half_v": None if not np.isfinite(peak) else peak,
            "rmse_second_half_v": rmse}


def main() -> None:
    t0 = time.perf_counter()
    rows = [classify(c, r) for r in R_GRID for c in C_FACTORS]
    # A load that already diverges at x0.70 is scanned upward to x1.00 so its boundary is found too.
    for r in R_GRID:
        if next(x for x in rows if x["load_ohm"] == r and x["c_scale"] == 0.70)["diverged"]:
            rows += [classify(round(0.71 + 0.01 * k, 2), r) for k in range(30)]
    per_load = []
    for r in R_GRID:
        rs = [x for x in rows if x["load_ohm"] == r]
        div = [x["c_scale"] for x in rs if x["diverged"]]
        stable = [x["c_scale"] for x in rs if not x["diverged"]]
        # monotone? every factor below the largest diverging one also diverges
        largest_div = max(div) if div else None
        monotone = largest_div is None or all(x["diverged"] for x in rs if x["c_scale"] <= largest_div)
        per_load.append({"load_ohm": r, "largest_diverging_c_scale": largest_div, "smallest_stable_c_scale": min(stable) if stable else None,
                         "monotone": monotone, "rmse_at_c_0_70_v": next(x["rmse_second_half_v"] for x in rs if x["c_scale"] == 0.70)})
    meta = {"generated_by": "experiments/measure_dpc_capacitor_divergence.py", "date": time.strftime("%Y-%m-%d"),
            "machine": f"{platform.system()} {platform.machine()}, Python {platform.python_version()}", "duration_s": DURATION_S,
            "reference_magnitude_v": REFERENCE_MAGNITUDE_V, "blowup_factor": BLOWUP, "c_factors": C_FACTORS, "loads_ohm": R_GRID,
            "runtime_s": round(time.perf_counter() - t0, 1)}
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "dpc_capacitor_divergence.json").write_text(json.dumps({"meta": meta, "per_load": per_load, "runs": rows}, indent=1))
    lines = ["# DPC loop vs. capacitor degradation (finding S-14)", "",
             f"Generated by `{meta['generated_by']}` on {meta['date']} ({meta['machine']}); raw values in [`dpc_capacitor_divergence.json`](dpc_capacitor_divergence.json).", "",
             f"Closed loop: datagen.runner VSC/DPC scenario (ScheduledDpcController, default reference {REFERENCE_MAGNITUDE_V:g} V, 50 Hz) on the degraded-capacitor plant "
             f"(sim/vsc_faults.py, no ESR), {DURATION_S:g} s per run. Capacitor factor {C_FACTORS[0]:.2f} → {C_FACTORS[-1]:.2f} in steps of 0.01; loads = the stable part of "
             f"measure_dpc_rmse_by_r_range.R_GRID. Diverged = a non-finite sample or |v_c| > {BLOWUP:g} × {REFERENCE_MAGNITUDE_V:g} V in the second half.", "",
             "Loads that already diverge at ×0.70 are scanned upward to ×1.00.", "",
             "| Load (Ω) | Largest diverging C factor | Smallest stable C factor | Divergence monotone in C | RMSE at C ×0.70 (V) |", "|---|---|---|---|---|"]
    for p in per_load:
        rmse = f"{p['rmse_at_c_0_70_v']:.2f}" if p["rmse_at_c_0_70_v"] is not None else "diverged"
        lines.append(f"| {p['load_ohm']:g} | {p['largest_diverging_c_scale'] if p['largest_diverging_c_scale'] is not None else 'none in range'} | "
                     f"{p['smallest_stable_c_scale'] if p['smallest_stable_c_scale'] is not None else 'none in range'} | {'yes' if p['monotone'] else 'no'} | {rmse} |")
    lines += ["", "Simulation only: the degraded plant is SPADE's synthetic capacitor model, and the controller is the DPC network trained on the nominal plant."]
    (OUT / "dpc_capacitor_divergence.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
