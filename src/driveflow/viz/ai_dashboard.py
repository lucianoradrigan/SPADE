"""IA tab (docs/design_ai_layer_transversal.md Sec. 5.1, Sec. 8 step 7): a standalone macro-phase
that CONSUMES data already generated by Fase A/B or uploaded by the user -- never a live control
surface itself (Sec. 5.1's "separar 'control en vivo' de 'análisis'"). Kept out of dashboard.py's
_render_fase_a/_render_fase_b to avoid growing that already-1600+-line file further (Sec. 9's
explicit instruction) -- dashboard.py only adds a landing-page card and a one-line dispatch to
_render_fase_ia() here. Must not import from driveflow.viz.dashboard (that module imports this
one) -- keeps the dependency one-directional.

Shows whichever of {classifier, regressor} the model registry (driveflow.ai.registry, Sec. 7) has
a promoted "pc"-tier run for, per domain -- gracefully saying "not trained yet" for the other
(Sec. 8's own status note: only the vsc_dpc regressor is registered so far, not yet a dc_motor
classifier). No Streamlit import in driveflow.ai.registry or the models/*/builder.py it calls, so
this module is the only place in this file that needs to be a real Streamlit session to run.
"""

